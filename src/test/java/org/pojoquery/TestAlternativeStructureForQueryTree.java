	public static Stream<QueryNode> findNodes(QueryNode node, Predicate<QueryNode> condition) {
		Stream<QueryNode> current = Stream.of(node);
		if (node instanceof TableNode tableNode && tableNode.children() != null) {
			current = Stream.concat(current, tableNode.children().stream().flatMap(child -> findNodes(child, condition)));
		}
		return current.filter(condition);
	}

	private TableInfo determinTableInfo(TypeModel type) {
		List<TableMapping> mapping = PojoMetadata.determineTableMapping(type);
		if (mapping.isEmpty()) {
			throw new IllegalArgumentException("Type " + type.getQualifiedName() + " is not an entity");
		}
		return new TableInfo(mapping.get(0).schemaName, mapping.get(0).tableName);
	}

	public Function<QueryNode, QueryNode> transformNodesRecursively(Function<QueryNode, QueryNode> transform) {
		return node -> {
			QueryNode transformed = transform.apply(node);
			if (transformed instanceof TableNode tableNode && tableNode.children() != null) {
				List<QueryNode> newChildren = tableNode.children().stream()
					.map(transformNodesRecursively(transform))
					.toList();
				return tableNode.withChildren(newChildren);
			} else {
				return transformed;
			}
		};
	}

