	private class DDLCollectorImpl implements DDLCollector {
		private HashMap<TableInfo, DDLTable> tables = new LinkedHashMap<>();
		private HashMap<DDLColumnKey, DDLColumn> columns = new LinkedHashMap<>();
		private HashMap<DDLColumnKey, List<FieldModel>> definingFields = new HashMap<>();
		private HashSet<DDLColumnKey> implicitForeignKeyColumns = new HashSet<>();
		private HashMap<DDLForeignKeyKey, DDLForeignKey> foreignKeys = new LinkedHashMap<>();
		@Override
		public void registerTable(TableInfo tableKey, List<DDLColumn> primaryKeyColumns) {
			tables.put(tableKey, new DDLTable(tableKey, primaryKeyColumns));
		}
		
		@Override
		public void registerColumn(TableInfo table, String columnName, FieldModel field) {
			// System.out.println("COLUMN: " + table.tableName() + "." + columnName + " Field: " + (field != null ? field.getName() : "[implicit foreign key]"));
			DDLColumnKey key = new DDLColumnKey(table, columnName);
			columns.put(key, new DDLColumn(key, field));
			if (field != null) {
				definingFields.computeIfAbsent(key, k -> new ArrayList<>()).add(field);
			} else {
				implicitForeignKeyColumns.add(key);
			}
		}

		@Override
		public void registerForeignKey(ForeignKeyInfo foreignKeyInfo) {
			DDLColumnKey ddlColumnKey = new DDLColumnKey(foreignKeyInfo.referringTable(), foreignKeyInfo.fkColumnName());
			registerColumn(foreignKeyInfo.referringTable(), foreignKeyInfo.fkColumnName(), foreignKeyInfo.foreignKeyField());
			foreignKeys.put(new DDLForeignKeyKey(ddlColumnKey), 
				new DDLForeignKey(ddlColumnKey, new DDLColumnKey(foreignKeyInfo.targetTable(), foreignKeyInfo.idColumnName()))
			);
		}
	}

	private List<String> generateCreateSchemaDDL(DbContext dbContext, RootNode... entities) {
		DDLCollectorImpl collector = new DDLCollectorImpl();
		for (RootNode entity : entities) {
			collectDDLForEntity(entity, collector);
		}
		
		List<String> statements = new ArrayList<>();
		
		// Generate CREATE TABLE statements
		for (DDLTable table : collector.tables.values()) {
			StringBuilder sb = new StringBuilder();
			sb.append("CREATE TABLE ");
			sb.append(dbContext.getQuoteStyle().quote(table.tableKey().tableName()));
			sb.append(" (\n");
			
			// Get columns for this table
			List<DDLColumn> tableColumns = collector.columns.values().stream()
				.filter(col -> col.columnKey().tableKey().equals(table.tableKey()))
				.toList();
			
			List<String> columnDefs = new ArrayList<>();
			for (DDLColumn col : tableColumns) {
				StringBuilder colDef = new StringBuilder();
				colDef.append("  ");
				colDef.append(dbContext.getQuoteStyle().quote(col.columnKey().columnName()));
				colDef.append(" ");
				
				// Determine SQL type
				if (col.field() != null) {
					boolean isAutoIncrement = table.primaryKeyColumns().contains(col) &&
						(col.field().getType().isSameType(new ReflectionTypeModel(Long.class)) || 
						col.field().getType().isSameType(new ReflectionTypeModel(long.class)));
					
					if (isAutoIncrement) {
						colDef.append(dbContext.getAutoIncrementKeyColumnType());
						colDef.append(" ");
						colDef.append(dbContext.getAutoIncrementSyntax());
					} else if (collector.foreignKeys.containsKey(new DDLForeignKeyKey(col.columnKey()))) {
						colDef.append(dbContext.getForeignKeyColumnType());
					} else {
						colDef.append(dbContext.mapJavaTypeToSql(col.field()));
					}
				} else {
					// Implicit foreign key column (from join table) - use BIGINT by default
					colDef.append(dbContext.getForeignKeyColumnType());
				}
				columnDefs.add(colDef.toString());
			}
			
			// Add primary key constraint if there are primary key columns
			if (!table.primaryKeyColumns().isEmpty()) {
				String pkColumns = table.primaryKeyColumns().stream()
					.map(pk -> dbContext.getQuoteStyle().quote(pk.columnKey().columnName()))
					.reduce((a, b) -> a + ", " + b)
					.orElse("");
				columnDefs.add("  PRIMARY KEY (" + pkColumns + ")");
			}
			
			sb.append(String.join(",\n", columnDefs));
			sb.append("\n)");
			statements.add(sb.toString());
		}
		
		// Generate ALTER TABLE statements for foreign keys
		for (DDLForeignKey fk : collector.foreignKeys.values()) {
			StringBuilder sb = new StringBuilder();
			sb.append("ALTER TABLE ");
			sb.append(dbContext.getQuoteStyle().quote(fk.referringColumn().tableKey().tableName()));
			sb.append(" ADD CONSTRAINT ");
			sb.append(dbContext.getQuoteStyle().quote("fk_" + fk.referringColumn().tableKey().tableName() + "_" + fk.referringColumn().columnName()));
			sb.append(" FOREIGN KEY (");
			sb.append(dbContext.getQuoteStyle().quote(fk.referringColumn().columnName()));
			sb.append(") REFERENCES ");
			sb.append(dbContext.getQuoteStyle().quote(fk.referencedIdColumn().tableKey().tableName()));
			sb.append(" (");
			sb.append(dbContext.getQuoteStyle().quote(fk.referencedIdColumn().columnName()));
			sb.append(")");
			statements.add(sb.toString());
		}
		
		return statements;
	}

	private void collectDDLForEntity(TableNode entity, DDLCollector collector) {
		TableInfo tableKey = new TableInfo(entity.tableInfo().schemaName(), entity.tableInfo().tableName());
		List<DDLColumn> primaryKeyColumns = entity.children().stream()
			.filter(child -> child instanceof PrimaryKey)
			.map(child -> (PrimaryKey) child)
			.map(pk -> new DDLColumn(new DDLColumnKey(tableKey, pk.columnName()), pk.field())) // placeholder type
			.toList();
		collector.registerTable(tableKey, primaryKeyColumns);

		for (QueryNode child : entity.children()) {
			if (child instanceof ScalarValue scalar) {
				collector.registerColumn(tableKey, scalar.columnName(), scalar.field());
			} else if (child instanceof PrimaryKeyField pkField) {
				collector.registerColumn(tableKey, pkField.columnName(), pkField.field());
			} else if (child instanceof Join ref) {
				collectDDLForEntity((TableNode)ref, collector);
				ForeignKeyInfo joinInfo = ref.join();
				collector.registerForeignKey(joinInfo);
			} else if (child instanceof JoinTableEntityCollection jte) {
				collectDDLForEntity(jte, collector);
				collector.registerTable(jte.join().joinTableInfo().tableInfo, List.of());
				collector.registerColumn(jte.join().joinTableInfo().tableInfo, jte.join().parentKey().fkColumnName(), null);
				collector.registerColumn(jte.join().joinTableInfo().tableInfo, jte.join().childKey().fkColumnName(), null);
				collector.registerForeignKey(jte.join().parentKey());
				collector.registerForeignKey(jte.join().childKey());
			}
		}
	}

	private RootNode buildQueryTreeForType(Class<?> clz) {
		ReflectionTypeModel rootType = new ReflectionTypeModel(clz);
		TableInfo tableInfo = determinTableInfo(rootType);
		QueryNode newTree = new RootNode(tableInfo.tableName(), rootType, tableInfo, null);
		QueryNode oldTree = null;
		do {
			oldTree = newTree;
			newTree = Optional.<QueryNode>ofNullable(oldTree)
				.map(transformNodesRecursively(this::addDeclaredFields))
				.map(transformNodesRecursively(this::addJointableEntityCollections))
				.map(transformNodesRecursively(this::addEntityCollections))
				.map(transformNodesRecursively(this::addEntityReferences))
				.map(transformNodesRecursively(this::addIdFields))
				.map(transformNodesRecursively(this::addScalarValues))
				.map(transformNodesRecursively(this::applyDefaultIdFieldNames))
				.map(transformNodesRecursively(this::applyDefaultForeignKeyColumnNames))
				.map(transformNodesRecursively(this::applyDefaultJoinConditions))
				.map(transformNodesRecursively(this::applyDefaultScalarExpressions))
				.map(transformNodesRecursively(this::makeSingleIdFieldsAutoIncrement))
				.orElse(null);
		} while(!oldTree.equals(newTree));

		return (RootNode) newTree;
	}

	record FieldValues(Map<String, Object> values, Map<String, Object> idValues, String autoGenIdField) {}

	private static FieldValues collectFields(RootNode tree, Object entity) {
		Map<String, Object> values = new LinkedHashMap<>();
		Map<String, Object> idValues = new LinkedHashMap<>();
		String autoGenIdField = null;

		for (QueryNode children : tree.children()) {
			if (children instanceof FieldNode fieldNode && fieldNode.field() != null) {
				String fieldName = fieldNode.field().getName();
				String columnName = fieldNode.columnName();
				Object value = getFieldValue(entity, fieldNode.field());

				if (fieldNode instanceof PrimaryKey pk) {
					if (pk.isAutoGenerated()) {
						if (value != null) {
							throw new IllegalStateException("Auto-generated ID field '" + fieldName + "' should not have a value");
						}
						autoGenIdField = fieldName;
					} else {
						if (value == null) {
							throw new IllegalStateException("ID field '" + fieldName + "' must have a value");
						}
					}
					idValues.put(columnName, value);
				} else if (fieldNode instanceof EntityReference entityRef) {
					// For entity references, we want to collect the ID value of the referenced entity
					if (value != null) {
						FieldModel referencedIdField = entityRef.children().stream()
							.filter(child -> child instanceof PrimaryKey)
							.map(child -> ((PrimaryKey) child).field())
							.findFirst()
							.orElseThrow(() -> new IllegalStateException("Referenced entity in field '" + fieldName + "' does not have an ID field"));
						Object referencedIdValue = getFieldValue(value, referencedIdField);
						if (referencedIdValue == null) {
							throw new IllegalStateException("Referenced entity in field '" + fieldName + "' has null ID value");
						}
						values.put(columnName, referencedIdValue);
					} else {
						values.put(columnName, null);
					}
				} else if (fieldNode instanceof ScalarValue) {
					values.put(columnName, value);
				}
			}
		}
		return new FieldValues(values, idValues, autoGenIdField);
	}

