	public QueryNode addDeclaredFields(QueryNode node) {
		return (node instanceof TableNode tableNode && tableNode.children() == null) ? 
			tableNode.withChildren(getFieldsOfEntity(tableNode.type()).stream()
				.map(f -> new EmptyFieldNodeImpl(f))
				.toList())
			:
			node;
	}

	private List<FieldModel> getFieldsOfEntity(TypeModel type) {
		List<TableMapping> mapping = PojoMetadata.determineTableMapping(type);
		return mapping.get(mapping.size() - 1).getFields().stream()
			.filter(f -> !PojoMetadata.isTransient(f))
			.toList();
	}

	private <C extends QueryNode> QueryNode transformChildren(QueryNode node, Predicate<QueryNode> childCondition, BiFunction<TableNode, C, QueryNode> transform) {
		return node instanceof TableNode parentNode && parentNode.children() != null ? 
			parentNode.withChildren(parentNode.children().stream()
				.map(child -> childCondition.test(child) ? transform.apply(parentNode, (C) child) : child)
				.toList())
			:
			node;
	}

	public QueryNode addEntityReferences(QueryNode node) {
		return transformChildren(node, 
			child -> child instanceof EmptyFieldNode emptyFieldNode && isEntity(emptyFieldNode.field().getType()),
			(TableNode parentNode, EmptyFieldNode emptyFieldNode) -> {
				String alias = AliasNaming.childAlias(
						node instanceof RootNode, 
						parentNode.alias(), 
						emptyFieldNode.field().getName());

				TypeModel referencedType = emptyFieldNode.field().getType();

				FieldModel childIdField = PojoMetadata.determineIdField(referencedType);

				return EntityReference.fromEmptyFieldNode(
						emptyFieldNode,
						alias,
						determinTableInfo(referencedType),
						emptyFieldNode.field(),
						parentNode.alias(),
						ForeignKeyInfo.fkInParent(parentNode.tableInfo(), parentNode.alias(), determinTableInfo(referencedType), alias, emptyFieldNode.field(), childIdField)
				);
			}
		);
	}


	public QueryNode addEntityCollections(QueryNode node) {
		return transformChildren(node,
			child -> child instanceof EmptyFieldNode emptyFieldNode && 
					isEntityCollection(emptyFieldNode.field().getType()),
			(TableNode parentNode, EmptyFieldNode emptyFieldNode) -> {
				TypeModel componentType = getCollectionComponentType(emptyFieldNode.field().getType());
				String alias = AliasNaming.childAlias(node instanceof RootNode, parentNode.alias(), emptyFieldNode.field().getName());
				TableInfo tableInfo = determinTableInfo(componentType);

				FieldModel idField = PojoMetadata.determineIdField(componentType);
				ForeignKeyInfo join = ForeignKeyInfo.fkInChild(parentNode.tableInfo(), parentNode.alias(), tableInfo, alias, idField);
				return EntityCollection.fromEmptyFieldNode(emptyFieldNode, alias, componentType, tableInfo, parentNode.alias(), join);
			}
		);
	}

	public QueryNode addJointableEntityCollections(QueryNode node) {
		return transformChildren(node,
			child -> child instanceof EmptyFieldNode emptyFieldNode && 
					isEntityCollection(emptyFieldNode.field().getType()) &&
					!Strings.isNullOrEmpty(emptyFieldNode.field().getAnnotationAttributeValue(Link.class, "linktable", String.class)),
			(TableNode parentNode, EmptyFieldNode emptyFieldNode) -> {
				TypeModel componentType = getCollectionComponentType(emptyFieldNode.field().getType());
				String alias = AliasNaming.childAlias(node instanceof RootNode, parentNode.alias(), emptyFieldNode.field().getName());
				TableInfo tableInfo = determinTableInfo(componentType);

				String linkTableName = emptyFieldNode.field().getAnnotationAttributeValue(Link.class, "linktable", String.class);
				String linkTableSchema = emptyFieldNode.field().getAnnotationAttributeValue(Link.class, "linkschema", String.class);

				String joinTableAlias = AliasNaming.childAlias(false, alias, linkTableName);

				TableInfo joinTable = new TableInfo(linkTableSchema.isEmpty() ? null : linkTableSchema, linkTableName);
				JoinTableInfo joinTableInfo = new JoinTableInfo(
					joinTable,
					joinTableAlias
				);

				JoinTableJoin join = new JoinTableJoin(
					joinTableInfo,
					ForeignKeyInfo.fkInChild(parentNode.tableInfo(), parentNode.alias(), joinTable, joinTableAlias, PojoMetadata.determineIdField(parentNode.type())),
					ForeignKeyInfo.fkInChild(tableInfo, alias, joinTable, joinTableAlias, PojoMetadata.determineIdField(componentType))
				);
				return JoinTableEntityCollection.fromEmptyFieldNode(emptyFieldNode, alias, componentType, tableInfo, join, parentNode.alias());
			}
		);
	}

